# §4.3 工作记忆格式化（Scratchpad Deep Formatting）
# =============================================================================
SCRATCHPAD_FORMAT_PROMPT = """
## 任务：格式化工作记忆（Scratchpad）

基于 action_nodes（操作节点）和当前 scratchpad 内容，重组输出格式化的 scratchpad。

### 输出格式（Markdown，4 段）
## 当前项目
- [正在进行的任务1，最多 3 项]
- ...

## 近期进展
- [已完成的任务，带日期前缀如 [09-08 10:30]]
- ...

## 未解决的问题
- [待解决的关键问题]
- ...

## 下一步
1. [动词开头的可执行步骤，最多 3 条]
2. ...
3. ...

### 格式化规则
- **内容不超过 2000 字符**（硬限制）
- 当前项目只放正在做的，最多 3 项
- 已完成的任务移到"近期进展"，带时间戳 [MM-DD HH:MM]
- 已解决/已放弃的问题从"未解决的问题"移除
- 下一步必须是可执行的具体动作（动词开头）
- 不重复之前记录过的内容（用省略号"..."表示延续）

### 质量要求
- 保持 scratchpad 的连续性（可追溯历史）
- 突出当前焦点（用户最关心的）
- 问题要具体，不要模糊（"处理中"不算具体问题）
- 下一步要有明确目标，不是"继续探索"
"""

