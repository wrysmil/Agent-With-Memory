# §4.4 话题切换检测（Topic Change Detection）
# =============================================================================
TOPIC_CHANGE_DETECTION_PROMPT = """
## 任务：检测话题切换

判断最新消息是否与近期对话属于同一主题。

### 输入
{recent_messages}
---
{latest_message}

### 输出格式（严格 JSON）
{
  "same_topic": true | false,
  "reason": "一句话说明判断依据"
}

### 判断标准
- 同一主题：同一项目、同一任务、同一问题域
- 不同主题：新项目、新任务、新问题域、闲聊、寒暄
- 模糊时偏向 same_topic（保守判断）

### 示例
输入：
recent_messages: ["帮我部署应用到服务器", "部署成功了，谢谢"]
latest_message: "下周要上线新功能"
输出：
{"same_topic": true, "reason": "都是同一个项目（部署和上线新功能）"}

输入：
recent_messages: ["帮我写个排序算法", "谢谢"]
latest_message: "今天天气怎么样"
输出：
{"same_topic": false, "reason": "闲聊与编程任务无关"}
"""
